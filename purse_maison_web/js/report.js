/**
 * Downloadable reports for the Dashboard and Sales Forecasting pages.
 *   PDF: builds a printable report (logo, title, details, figures, charts) and opens the browser's
 *        print window, where staff choose "Save as PDF".
 *   CSV: downloads the same figures as a .csv file that opens in Excel.
 * Both follow the filters currently selected on the page. Nothing is sent to the database.
 * Load after js/pages/forecasting.js.
 */

const ReportExport = {
  LOGO: 'assets/images/LOGO_PURSE_MAISON-removebg-preview.png',

  // ---------------------------------------------------------------- helpers
  now() { return new Date(); },
  generatedAt() { return DataStore.formatDateTime(this.now().toISOString()); },
  fileDate() {
    const d = this.now();
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  },
  generatedBy() {
    const u = Session.currentUser || {};
    return `${u.fullName || u.username || 'Staff'} · ${Session.roleLabel()}`;
  },
  peso(n) { return `₱${formatAmount(Number(n) || 0)}`; },
  round(n) { return Math.round((Number(n) || 0) * 100) / 100; },

  /** A chart already drawn on the page, as an image for the PDF (skipped if the chart is not there). */
  chartImage(canvasId, title) {
    const canvas = document.getElementById(canvasId);
    if (!canvas || !canvas.width) return '';
    try {
      return `<div class="rpt-chart"><img src="${canvas.toDataURL('image/png')}" alt="${escapeHtml(title)}"></div>`;
    } catch (err) {
      return '';
    }
  },

  table(headers, rows, numericFrom = 1) {
    return `<table class="rpt-table"><thead><tr>${headers.map((h, i) => `<th${i >= numericFrom ? ' class="num"' : ''}>${escapeHtml(h)}</th>`).join('')}</tr></thead>
      <tbody>${rows.length ? rows.map((r) => `<tr>${r.map((c, i) => `<td${i >= numericFrom ? ' class="num"' : ''}>${escapeHtml(c)}</td>`).join('')}</tr>`).join('')
        : `<tr><td colspan="${headers.length}" class="rpt-empty">No data for the selected filters.</td></tr>`}</tbody></table>`;
  },

  header(title, filters) {
    return `
      <div class="rpt-header">
        <img src="${this.LOGO}" alt="Purse Maison">
        <div>
          <div class="rpt-title">${escapeHtml(title)}</div>
          <div class="rpt-sub">Centralized Consignment Analytics and Sales Forecasting System</div>
        </div>
      </div>
      <table class="rpt-meta">
        <tr><td>Generated</td><td>${escapeHtml(this.generatedAt())}</td></tr>
        <tr><td>Generated by</td><td>${escapeHtml(this.generatedBy())}</td></tr>
        ${filters.map(([k, v]) => `<tr><td>${escapeHtml(k)}</td><td>${escapeHtml(v)}</td></tr>`).join('')}
      </table>`;
  },

  section(title, body) { return `<div class="rpt-section"><h2>${escapeHtml(title)}</h2>${body}</div>`; },

  /** Puts the report into the page, opens the print window, and removes it again afterwards. */
  print(html) {
    let box = document.getElementById('print-report');
    if (!box) {
      box = document.createElement('div');
      box.id = 'print-report';
      document.body.appendChild(box);
    }
    box.innerHTML = `${html}<div class="rpt-footer">Purse Maison · Internal report · Figures follow the filters shown above.</div>`;
    document.body.classList.add('printing-report');
    const cleanup = () => {
      document.body.classList.remove('printing-report');
      box.innerHTML = '';
      window.removeEventListener('afterprint', cleanup);
    };
    window.addEventListener('afterprint', cleanup);
    // Wait for the logo and chart images before printing
    const images = [...box.querySelectorAll('img')];
    Promise.all(images.map((img) => (img.complete ? null : new Promise((r) => { img.onload = r; img.onerror = r; }))))
      .then(() => setTimeout(() => window.print(), 100));
  },

  /** One CSV value: quoted, and protected so Excel never runs it as a formula. */
  csvCell(value) {
    let s = value === null || value === undefined ? '' : String(value);
    if (typeof value === 'string' && /^[=+\-@]/.test(s)) s = `'${s}`;
    return `"${s.replace(/"/g, '""')}"`;
  },

  /** sections: [{ title, headers, rows }] → one CSV file with a blank line between sections. */
  downloadCsv(name, title, filters, sections) {
    const lines = [
      [title], ['Generated', this.generatedAt()], ['Generated by', this.generatedBy()],
      ...filters, [],
    ];
    for (const s of sections) {
      lines.push([s.title], s.headers, ...(s.rows.length ? s.rows : [['No data for the selected filters.']]), []);
    }
    const csv = lines.map((r) => r.map((c) => this.csvCell(c)).join(',')).join('\r\n');
    const blob = new Blob(['\uFEFF' + csv], { type: 'text/csv;charset=utf-8' }); // BOM so Excel shows ₱ correctly
    const link = document.createElement('a');
    link.href = URL.createObjectURL(blob);
    link.download = `purse-maison-${name}-${this.fileDate()}.csv`;
    document.body.appendChild(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(link.href), 1000);
    showToast('Report downloaded.');
  },

  /** One "Download Report" button: asks for the format, then makes the PDF or CSV. */
  choose(title, onPdf, onCsv) {
    const overlay = openModal({
      title,
      bodyHtml: `
        <p class="cell-muted" style="font-size:12.5px; margin-bottom:12px;">The report follows the filters currently selected.</p>
        <div class="report-options">
          <button type="button" class="report-option" data-format="pdf"><i class="fa-solid fa-file-pdf"></i><span><strong>PDF</strong></span></button>
          <button type="button" class="report-option" data-format="csv"><i class="fa-solid fa-file-csv"></i><span><strong>CSV</strong></span></button>
      </div>`,
    });
    overlay.querySelectorAll('[data-format]').forEach((btn) => btn.addEventListener('click', () => {
      closeModal();
      if (btn.dataset.format === 'pdf') onPdf();
      else onCsv();
    }));
  },

  dashboard() { this.choose('Download Dashboard Report', () => this.dashboardPdf(), () => this.dashboardCsv()); },
  forecast() { this.choose('Download Sales Forecast Report', () => this.forecastPdf(), () => this.forecastCsv()); },
  inventory() { this.choose('Download Inventory Report', () => this.inventoryPdf(), () => this.inventoryCsv()); },

  // -------------------------------------------------------------- dashboard
  dashboardData() {
    const page = DashboardPage;
    const stats = page.computeStats();
    const brandNames = page.filterBrands === null ? 'All brands'
      : page.brandOptions().filter(([k]) => page.filterBrands.includes(k)).map(([, n]) => n).join(', ');
    const filters = [['Period', page.periodLabel()], ['Brands', brandNames]];
    const kpis = [
      [`Total Sales (${page.kpiPeriod()})`, this.peso(stats.periodTotal), this.round(stats.periodTotal)],
      [`Items Sold (${page.kpiPeriod()})`, String(stats.periodUnits), stats.periodUnits],
      ['Active Consigned Items', String(stats.activeConsignedItems), stats.activeConsignedItems],
      ['Monthly Sales Growth', `${stats.growthPercent.toFixed(1)}%`, this.round(stats.growthPercent)],
      ['Average Display Duration (days)', stats.avgDisplayDuration === null ? '—' : String(Math.round(stats.avgDisplayDuration)), stats.avgDisplayDuration === null ? '' : Math.round(stats.avgDisplayDuration)],
      ['Inventory Turnover Rate', `${stats.turnoverRate.toFixed(2)}x`, this.round(stats.turnoverRate)],
      ['Total Item Inquiries', String(stats.totalInquiries), stats.totalInquiries],
      ['Fast Moving Items', String(stats.fastMovingCount), stats.fastMovingCount],
      ['Slow Moving Items', String(stats.slowMovingCount), stats.slowMovingCount],
    ];
    const salesRows = stats.buckets.map((b, i) => [b.label, stats.monthlyTotals[i]]);
    const interactionRows = stats.buckets.map((b, i) => [b.label, ...INTERACTION_SERIES.map(([field]) => stats.interactions[field][i])]);
    const statusRows = Object.entries(stats.statusCounts);
    return { page, stats, filters, kpis, salesRows, interactionRows, statusRows };
  },

  dashboardPdf() {
    const d = this.dashboardData();
    const notes = d.page.chartNotes(d.stats);
    const insights = d.page.buildInsights(d.stats);
    const html = [
      this.header('Dashboard Report', d.filters),
      this.section('Key Performance Indicators', this.table(['Indicator', 'Value'], d.kpis.map(([k, v]) => [k, v]))),
      this.section('Sales Overview', `${this.chartImage('chart-sales-overview', 'Sales Overview')}<p class="rpt-note">${escapeHtml(notes.overview || '')}</p>
        ${this.table(['Period', 'Revenue'], d.salesRows.map(([l, v]) => [l, this.peso(v)]))}`),
      this.section('Actual vs Period Average', `${this.chartImage('chart-actual-vs-average', 'Actual vs Period Average')}<p class="rpt-note">${escapeHtml(notes.average || '')}</p>`),
      this.section('Customer Interactions', `${this.chartImage('chart-customer-interactions', 'Customer Interactions')}<p class="rpt-note">${escapeHtml(notes.interactions || '')}</p>
        ${this.table(['Period', ...INTERACTION_SERIES.map(([, label]) => label)], d.interactionRows.map((r) => r.map(String)))}`),
      this.section('Inventory Performance', `${this.chartImage('chart-inventory-performance', 'Inventory Performance')}<p class="rpt-note">${escapeHtml(notes.inventory || '')}</p>
        ${this.table(['Status', 'Items'], d.statusRows.map(([k, v]) => [k, String(v)]))}`),
      this.section('Key Insights', `<ul class="rpt-list">${insights.map(([label, text]) => `<li><strong>${escapeHtml(label)}:</strong> ${escapeHtml(text)}</li>`).join('')}</ul>`),
    ].join('');
    this.print(html);
  },

  dashboardCsv() {
    const d = this.dashboardData();
    this.downloadCsv('dashboard', 'Purse Maison - Dashboard Report', d.filters, [
      { title: 'Key Performance Indicators', headers: ['Indicator', 'Value'], rows: d.kpis.map(([k, , raw]) => [k, raw]) },
      { title: 'Sales Overview', headers: ['Period', 'Revenue (PHP)'], rows: d.salesRows.map(([l, v]) => [l, this.round(v)]) },
      { title: 'Customer Interactions', headers: ['Period', ...INTERACTION_SERIES.map(([, label]) => label)], rows: d.interactionRows },
      { title: 'Inventory Performance', headers: ['Status', 'Items'], rows: d.statusRows },
    ]);
  },

  // ------------------------------------------------------------ forecasting
  forecastData() {
    const page = ForecastingPage;
    const meta = DB.forecastMeta;
    const rows = page.visibleRows();
    const months = page.monthsShown();
    const trendNames = { increasing: 'Increasing', stable: 'Stable', decreasing: 'Decreasing' };
    const filters = [
      ['Brands', page.selectedBrands === null ? 'All brands' : rows.map((r) => r.brand).join(', ') || 'None'],
      ['Trend', page.selectedTrends === null ? 'All trends' : page.selectedTrends.map((t) => trendNames[t]).join(', ')],
      ['Forecast period', months ? `Next ${months} months` : 'No forecast yet'],
      ['Forecast generated', meta.generatedAt ? DataStore.formatDateTime(meta.generatedAt) : '—'],
      ['Model', `ARIMA${meta.avgMae !== null ? ` · average error (MAE) ${this.peso(meta.avgMae)}` : ''}`],
    ];
    const brandRows = rows.map((f) => [f.brand, f.historicalValue, f.projectedValue, f.projectedGrowthPercent, trendNames[f.trend] || f.trend, f.mae]);
    const monthly = [];
    for (const f of rows) {
      DB.forecastRows.filter((r) => r.brandKey === f.brandKey).sort((a, b) => a.month - b.month).slice(0, months)
        .forEach((r) => monthly.push([f.brand, `${MONTH_ABBREV[r.month.getMonth()]} ${r.month.getFullYear()}`, r.revenue, r.lower, r.upper]));
    }
    const alerts = page.visibleAlerts(rows).map((a) => a.description);
    return { page, filters, brandRows, monthly, alerts };
  },

  forecastPdf() {
    const d = this.forecastData();
    const text = (id) => (document.getElementById(id) || {}).textContent || '';
    const pct = (g) => (g === null ? '—' : `${g >= 0 ? '+' : ''}${g}%`);
    const html = [
      this.header('Sales Forecast Report', d.filters),
      this.section('Sales Trend (Actual vs Projected)', `${this.chartImage('chart-sales-trend', 'Sales Trend (Actual vs Projected)')}<p class="rpt-note">${escapeHtml(text('trend-insight'))}</p>`),
      this.section('Projected Growth by Brand', `${this.chartImage('chart-brand-forecast', 'Projected Growth by Brand')}<p class="rpt-note">${escapeHtml(text('growth-insight'))}</p>`),
      this.section('Brand Forecasts', this.table(['Brand', 'Historical', 'Projected', 'Growth', 'Trend', 'Avg. Error (MAE)'],
        d.brandRows.map(([b, h, p, g, t, mae]) => [b, this.peso(h), this.peso(p), pct(g), t, mae === null ? '—' : this.peso(mae)]))),
      this.section('Monthly Forecast by Brand', this.table(['Brand', 'Month', 'Projected', 'Likely low', 'Likely high'],
        d.monthly.map(([b, m, v, lo, hi]) => [b, m, this.peso(v), lo === null ? '—' : this.peso(lo), hi === null ? '—' : this.peso(hi)]), 2)),
      this.section('Prediction Alerts', d.alerts.length ? `<ul class="rpt-list">${d.alerts.map((a) => `<li>${escapeHtml(a)}</li>`).join('')}</ul>` : '<p class="rpt-note">No alerts for the selected filters.</p>'),
      '<p class="rpt-note">Forecasts are estimates based on past monthly sales and are meant to support, not replace, management decisions.</p>',
    ].join('');
    this.print(html);
  },

  forecastCsv() {
    const d = this.forecastData();
    this.downloadCsv('sales-forecast', 'Purse Maison - Sales Forecast Report', d.filters, [
      { title: 'Brand Forecasts', headers: ['Brand', 'Historical (PHP)', 'Projected (PHP)', 'Growth %', 'Trend', 'Avg. Error MAE (PHP)'],
        rows: d.brandRows.map(([b, h, p, g, t, mae]) => [b, this.round(h), this.round(p), g === null ? '' : g, t, mae === null ? '' : this.round(mae)]) },
      { title: 'Monthly Forecast by Brand', headers: ['Brand', 'Month', 'Projected (PHP)', 'Likely low (PHP)', 'Likely high (PHP)'],
        rows: d.monthly.map(([b, m, v, lo, hi]) => [b, m, this.round(v), lo === null ? '' : this.round(lo), hi === null ? '' : this.round(hi)]) },
      { title: 'Prediction Alerts', headers: ['Alert'], rows: d.alerts.map((a) => [a]) },
    ]);
  },
  
  // -------------------------------------------------------------- inventory
  inventoryData() {
    const page = InventoryPage;
    const all = DB.inventory;
    const items = page.filterAndSortItems(all);
    const count = (list, status) => list.filter((i) => i.status === status).length;
    const expiring = DB.pipelineItems.filter((i) => {
      if (!i.listing || i.listing.inventory_status !== 'published' || i.sale || i.withdrawal) return false;
      const c = ConsignmentFlow.contractInfo(i);
      return c && c.left <= 7;
    }).length;
    const statusNames = { available: 'Available', reserved: 'Reserved', sold: 'Sold', rejected: 'Rejected' };
    const txnNames = { none: 'None', pending: 'Pending', cancelled: 'Cancelled', completed: 'Completed' };
    const sortNames = { recently: 'Recently Added', oldest: 'Oldest First', 'price-high': 'Price High to Low', 'price-low': 'Price Low to High', alphabetical: 'Brand A-Z' };
    const filters = [
      ['Search', page.searchKeyword || 'None'],
      ['Date added', dateRangeLabel(page.filterRange, 'day', 'all')],
      ['Brands', page.filterBrands === null ? 'All brands' : page.filterBrands.join(', ') || 'None'],
      ['Status', page.filterStatuses === null ? 'All statuses' : page.filterStatuses.map((s) => statusNames[s] || s).join(', ') || 'None'],
      ['Sorted by', sortNames[page.sortBy] || page.sortBy],
      ['Items in this report', String(items.length)],
    ];
    const kpis = [
      ['Total Items', all.length],
      ['Available Items', count(all, 'available')],
      ['Reserved Items', count(all, 'reserved')],
      ['Expiring Contracts', expiring],
    ];
    const statusRows = Object.entries(statusNames).map(([key, label]) => [label, count(items, key)]);
    const byLocation = {};
    items.forEach((i) => { byLocation[i.location] = (byLocation[i.location] || 0) + 1; });
    const locationRows = Object.entries(byLocation).sort((a, b) => b[1] - a[1]);

    // The slowest sales among the items in this report (days from being added to being sold)
    const byId = Object.fromEntries(items.map((i) => [i.id, i]));
    const slow = [];
    for (const t of DB.salesTransactions) {
      const item = t.itemId && byId[t.itemId];
      const added = item && parseDateAdded(item.dateAdded);
      if (!added) continue;
      const days = Math.round((t.date - added) / 86400000);
      if (days >= 0) slow.push([`${item.brand} ${item.category}`, days, item.price]);
    }
    slow.sort((a, b) => b[1] - a[1]);

    const listRows = items.map((i) => [
      i.id, i.brand, i.category, i.condition, statusNames[i.status] || i.status, i.location, i.dateAdded,
      txnNames[i.transactionStatus] || i.transactionStatus, i.price,
      i.price === '—' ? '' : parseAmountString(i.price),
    ]);
    return { filters, kpis, statusRows, locationRows, slow: slow.slice(0, 5), listRows };
  },

  inventoryPdf() {
    const d = this.inventoryData();
    const html = [
      this.header('Inventory Report', d.filters),
      this.section('Inventory Overview (all items)', this.table(['Indicator', 'Value'], d.kpis.map(([k, v]) => [k, String(v)]))),
      this.section('Items by Status', this.table(['Status', 'Items'], d.statusRows.map(([k, v]) => [k, String(v)]))),
      this.section('Inventory by Location', this.table(['Location', 'Items'], d.locationRows.map(([k, v]) => [k, String(v)]))),
      this.section('Inventory Turnover Rate', this.chartImage('chart-turnover', 'Inventory Turnover Rate')),
      this.section('Slowest-Moving Items', this.table(['Item', 'Days to sell', 'Price'], d.slow.map(([n, days, p]) => [n, String(days), p]))),
      this.section(`Inventory List (${d.listRows.length} items)`,
        this.table(['Item ID', 'Brand', 'Category', 'Condition', 'Status', 'Location', 'Date Added', 'Transaction', 'Price'],
          d.listRows.map((r) => r.slice(0, 9)), 99)),
    ].join('');
    this.print(html);
  },

  inventoryCsv() {
    const d = this.inventoryData();
    this.downloadCsv('inventory', 'Purse Maison - Inventory Report', d.filters, [
      { title: 'Inventory Overview (all items)', headers: ['Indicator', 'Value'], rows: d.kpis },
      { title: 'Items by Status', headers: ['Status', 'Items'], rows: d.statusRows },
      { title: 'Inventory by Location', headers: ['Location', 'Items'], rows: d.locationRows },
      { title: 'Inventory List', headers: ['Item ID', 'Brand', 'Category', 'Condition', 'Status', 'Location', 'Date Added', 'Transaction Status', 'Price (PHP)'],
        rows: d.listRows.map((r) => [...r.slice(0, 8), r[9]]) },
    ]);
  },
};